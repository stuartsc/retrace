import Foundation

/// Separate context data only. Never receives or mutates the canonical recording connection.
public protocol ContextStoreProtocol: Actor, CompanionSourceStoreProtocol {
    func initialize() async throws
    func close() async throws
    func contextStoreID() async throws -> UUID

    /// Identical client/request retries return the original committed creation receipt.
    /// Re-read marker(id:includeDeleted:) before displaying a current-state acknowledgement.
    func createManualMarker(_ command: ManualTimelineMarkerCommand) async throws -> TimelineMarker
    /// Returns an immutable edit receipt; a retry never restores a deleted marker.
    func updateMarker(_ command: TimelineMarkerEditCommand) async throws -> TimelineMarker
    func marker(id: UUID, includeDeleted: Bool) async throws -> TimelineMarker?
    func listMarkers(_ query: TimelineMarkerQuery) async throws -> TimelineMarkerPage
    func setMarkerDeleted(id: UUID, expectedRevision: UUID, deleted: Bool) async throws -> TimelineMarker

    /// nil expectedRevision means create; updates require the current revision. Saved revisions are generated by the store.
    func saveKeywordRule(_ rule: KeywordRule, expectedRevision: UUID?) async throws -> KeywordRule
    func listKeywordRules(afterID: UUID?, limit: Int) async throws -> [KeywordRule]

    /// A proposal cannot overwrite a manual or pinned range, even with its current revision.
    func saveContextRange(markerID: UUID, range: MarkerContextRange, expectedRevision: UUID?, expectedMarkerRevision: UUID?) async throws -> MarkerContextRange
    func listContextRanges(markerID: UUID, limit: Int) async throws -> [MarkerContextRange]
    func contextProposalHead(markerID: UUID) async throws -> ContextProposalHead?
    func applyContextProposal(_ command: ContextProposalCommand) async throws -> ContextProposalReceipt
    func contextProposal(jobID: String) async throws -> RetainedContextProposal?
    func contextRangeHistory(markerID: UUID, afterSequence: Int64, limit: Int) async throws -> [ContextRangeRevision]

    /// Returns the immutable command receipt. App callers re-read spokenMarkerState before presentation.
    func applySpokenObservation(_ command: SpokenObservationCommand) async throws -> SpokenMarkerReceipt
    func spokenMarkerState(occurrenceID: UUID) async throws -> SpokenMarkerReceipt?
    func spokenObservation(occurrenceID: UUID) async throws -> SpokenMarkerObservation?
    func spokenObservations(occurrenceID: UUID, afterSequence: Int64, limit: Int) async throws -> [SpokenMarkerObservation]
    func registerAudioManifest(_ manifest: AudioMediaManifest) async throws -> AudioMediaManifest
    func audioManifest(relativePath: String) async throws -> AudioMediaManifest?
    func audioManifests(intersecting anchor: SpokenMarkerAnchor, limit: Int) async throws -> [AudioMediaManifest]
    func audioManifests(intersecting range: NativeAudioSampleRange, limit: Int) async throws -> [AudioMediaManifest]
}

public extension ContextStoreProtocol {
    func audioManifests(intersecting range: NativeAudioSampleRange, limit: Int) async throws -> [AudioMediaManifest] {
        throw ContextStoreError.invalidInput
    }
    func saveContextRange(markerID: UUID, range: MarkerContextRange, expectedRevision: UUID?) async throws -> MarkerContextRange {
        try await saveContextRange(markerID: markerID, range: range, expectedRevision: expectedRevision, expectedMarkerRevision: nil)
    }
}
